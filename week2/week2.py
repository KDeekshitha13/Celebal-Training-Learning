import logging

def ingest_data(input_file, output_file):
    try:
        logging.info("Reading CSV file")
        df = pd.read_csv(input_file)

        logging.info("CSV file loaded successfully")

        # Clean column names
        df.columns = (
            df.columns.str.lower()
            .str.strip()
            .str.replace(" ", "_")
        )
        logging.info("Column names cleaned")

        # Remove duplicates
        df = df.drop_duplicates()
        logging.info("Duplicate records removed")

        # Handle missing values
        df = df.dropna(subset=['vendorid'])

        for col in df.columns:
            if df[col].isnull().any():
                if pd.api.types.is_numeric_dtype(df[col]):
                    df[col] = df[col].fillna(df[col].median())
                else:
                    df[col] = df[col].fillna("Unknown")

        logging.info("Missing values handled")

        # Convert date columns
        date_columns = [
            'tpep_pickup_datetime',
            'tpep_dropoff_datetime'
        ]

        for col in date_columns:
            df[col] = pd.to_datetime(df[col], errors='coerce')

        logging.info("Date columns converted")

        # Save as Parquet
        df.to_parquet(output_file, engine="pyarrow", index=False)

        logging.info("Data saved as Parquet successfully")
        print("Ingestion completed successfully!")

        return df

    except Exception as e:
        logging.error(f"Data ingestion failed: {e}")
        print("Error:", e)

